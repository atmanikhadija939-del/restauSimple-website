/* App State Variables */
let currentLang = 'fr';
let currentCategory = 'plats';
let quizStep = 0;
let quizAnswers = [];

/* Dynamic Language Switcher  */
function changeLanguage(lang) {
  currentLang = lang;
  
  //s
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';

  // 
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.textContent.toLowerCase() === lang);
  });

  // 
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    }
  });

  // 
  populateSelects();

  // 
  renderMenu(currentCategory);

  // 
  const body = document.getElementById('reco-body');
  if (body && body.classList.contains('open')) {
    quizStep = 0;
    quizAnswers = [];
    renderQuiz();
  }
}

function populateSelects() {
  const t = translations[currentLang];
  
  // 
  const guestsSelect = document.getElementById('select-guests');
  if (guestsSelect) {
    guestsSelect.innerHTML = t.guests_opts.map((opt, i) => 
      `<option ${i === 1 ? 'selected' : ''}>${opt}</option>`
    ).join('');
  }

  // 
  const occasionSelect = document.getElementById('select-occasion');
  if (occasionSelect) {
    occasionSelect.innerHTML = t.occasion_opts.map((opt, i) => 
      `<option value="${i === 0 ? '' : opt}">${opt}</option>`
    ).join('');
  }
}

/* Recommendation */
function getRecommendation(answers) {
  const menu = menuDataMultilingual[currentLang];
  if (answers[0] === translations[currentLang].q1_opts[2]) return menu.find(m => m.id === 'couscous-royal');
  if (answers[0] === translations[currentLang].q1_opts[1]) return menu.find(m => m.id === 'tajine-poisson');
  if (answers[1] === translations[currentLang].q2_opts[0]) return menu.find(m => m.id === 'pastilla-poulet');
  return menu.find(m => m.id === 'tajine-agneau');
}

/*  Page Navigation  */
function showPage(id) {
  document.querySelectorAll('.page').forEach(p => p.classList.remove('active'));
  document.getElementById('page-' + id).classList.add('active');

  document.querySelectorAll('.nav-link').forEach(l => l.classList.remove('active'));
  const nl = document.getElementById('nav-' + id);
  if (nl) nl.classList.add('active');

  document.querySelectorAll('.mobile-link').forEach(l => l.classList.remove('active'));
  const ml = document.getElementById('mob-' + id);
  if (ml) ml.classList.add('active');

  window.scrollTo({ top: 0, behavior: 'smooth' });

  if (id === 'menu') renderMenu(currentCategory);
}

