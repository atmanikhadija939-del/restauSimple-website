/* Menu Rendering */
function renderMenu(cat) {
  currentCategory = cat;
  const grid = document.getElementById('menu-grid');
  const menuList = menuDataMultilingual[currentLang];
  const items = menuList.filter(m => m.cat === cat);
  const t = translations[currentLang];

  grid.innerHTML = items.map(item => `
    <div class="menu-card">
      <div class="card-img">
        <img src="${item.img}" alt="${item.name}" loading="lazy" />
        <div class="card-img-overlay"></div>
        <div class="card-badge-cal">${item.calories === 0 ? '0 kcal' : item.calories + ' kcal'}</div>
        <div class="card-badge-cat">${item.cat}</div>
      </div>
      <div class="card-body">
        <div class="card-header">
          <h3 class="card-name">${item.name}</h3>
          <span class="card-price">${item.price} ${t.currency}</span>
        </div>
        <p class="card-desc">${item.desc}</p>
        <p class="card-ingr-label">${t.ingr_label}</p>
        <ul class="card-ingr-list">
          ${item.ingredients.map(ing => `
            <li class="card-ingr-item"><div class="card-ingr-dot"></div>${ing}</li>
          `).join('')}
        </ul>
        ${item.wine ? `
        <div class="card-wine">
          <p class="card-wine-label">${t.match_label}</p>
          <div class="card-wine-name"><div class="wine-dot"></div>${item.wine}</div>
        </div>` : ''}
      </div>
    </div>
  `).join('');
}

function filterMenu(cat) {
  document.querySelectorAll('.tab-btn').forEach(b => b.classList.remove('active'));
  document.getElementById('tab-' + cat).classList.add('active');
  renderMenu(cat);
}

/* Recommendation Tool */
function toggleReco() {
  const body = document.getElementById('reco-body');
  const plus = document.getElementById('reco-plus');
  const isOpen = body.classList.toggle('open');
  plus.classList.toggle('open', isOpen);
  if (isOpen) { quizStep = 0; quizAnswers = []; renderQuiz(); }
}

function renderQuiz() {
  const body = document.getElementById('reco-body');
  const t = translations[currentLang];
  const questions = [
    { q: t.q1, opts: t.q1_opts },
    { q: t.q2, opts: t.q2_opts },
    { q: t.q3, opts: t.q3_opts }
  ];

  const q = questions[quizStep];
  const bars = questions.map((_, i) => `<div class="quiz-bar${i <= quizStep ? ' done' : ''}"></div>`).join('');
  body.innerHTML = `
    <div class="quiz-progress">${bars}</div>
    <p class="quiz-step-label">Question ${quizStep + 1} / ${questions.length}</p>
    <h4 class="quiz-question">${q.q}</h4>
    <div class="quiz-options">
      ${q.opts.map(opt => `<button class="quiz-option" onclick="quizAnswer('${opt}')">${opt}</button>`).join('')}
    </div>
  `;
}

function quizAnswer(opt) {
  quizAnswers.push(opt);
  if (quizStep < 2) {
    quizStep++;
    renderQuiz();
  } else {
    renderRecoResult();
  }
}

function renderRecoResult() {
  const item = getRecommendation(quizAnswers);
  const body = document.getElementById('reco-body');
  const t = translations[currentLang];

  body.innerHTML = `
    <div class="reco-result">
      <img class="reco-result-img" src="${item.img}" alt="${item.name}" />
      <div class="reco-result-info">
        <p class="reco-result-label">${t.our_sugg}</p>
        <h4 class="reco-result-name">${item.name}</h4>
        <p class="reco-result-desc">${item.desc}</p>
        <div class="reco-result-meta">
          <span class="reco-result-price">${item.price} ${t.currency}</span>
          <span class="reco-result-cal">${item.calories} kcal</span>
        </div>
        <button class="reco-restart" onclick="quizStep=0;quizAnswers=[];renderQuiz()">${t.restart_quiz}</button>
      </div>
    </div>
  `;
}

